from pathlib import Path
import os
from PIL import ImageFont
root = Path(__file__).resolve().parents[1]
sdk = Path(os.environ.get('DIVE_NCS_ROOT', str(Path.home() / 'ncs/v3.4.1')))
font = ImageFont.truetype(str(sdk / 'modules/lib/gui/lvgl/scripts/built_in_font/Montserrat-Medium.ttf'), 14)
mask, (left, top) = font.getmask2('é', mode='L', anchor='ls')
width, height = mask.size
alpha = [(v + 8) // 17 for v in bytes(mask)]
bitmap = [(alpha[i] << 4) | (alpha[i+1] if i+1 < len(alpha) else 0) for i in range(0,len(alpha),2)]
text = '''/* Montserrat Medium 14, U+00E9 only. Generated by tools/build_desaturation_font.py.
 * Other glyphs use the existing LVGL Montserrat 14 fallback.
 * Copyright 2011 The Montserrat Project Authors (https://github.com/JulietaUla/Montserrat)
 * Licensed under the SIL Open Font License, Version 1.1.
 * See ../../licenses/Montserrat-OFL.txt for the complete copyright and license. */
#include <lvgl.h>
static const uint8_t bitmap[] = {'''+','.join(hex(v) for v in bitmap)+'''};
static const lv_font_fmt_txt_glyph_dsc_t glyphs[] = {{0},
'''+f'{{.bitmap_index=0,.adv_w={round(font.getlength("é")*16)},.box_w={width},.box_h={height},.ofs_x={left},.ofs_y={-top-height}}}'+'''};
static const lv_font_fmt_txt_cmap_t cmaps[] = {{.range_start=233,.range_length=1,.glyph_id_start=1,.type=LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY}};
static const lv_font_fmt_txt_dsc_t descriptor = {.glyph_bitmap=bitmap,.glyph_dsc=glyphs,.cmaps=cmaps,.cmap_num=1,.bpp=4};
const lv_font_t watch_montserrat_french_14 = {.get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,.get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,.line_height=16,.base_line=3,.dsc=&descriptor,.fallback=&lv_font_montserrat_14};
'''
(root / 'src/assets/montserrat_french_14.c').write_text(text)

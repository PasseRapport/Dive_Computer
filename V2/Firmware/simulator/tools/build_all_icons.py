# 7. COMPASS (Boussole — aiguille inclinée à 35°)
def draw_compass(d, S):
    cx, cy = 22 * S, 22 * S
    outer_r = 19 * S
    ring_w = 2.4 * S
    d.ellipse([(cx - outer_r, cy - outer_r), (cx + outer_r, cy + outer_r)], outline=255, width=int(ring_w))
    d.polygon([(cx - 3.8*S, cy - outer_r + ring_w - 0.5*S),
               (cx + 3.8*S, cy - outer_r + ring_w - 0.5*S),
               (cx, cy - outer_r + ring_w + 4.5*S)], fill=255)
    tick_len = 3.2 * S
    tick_w = int(1.8 * S)
    d.line([(cx, cy + outer_r - ring_w), (cx, cy + outer_r - ring_w - tick_len)], fill=255, width=tick_w)
    d.line([(cx + outer_r - ring_w, cy), (cx + outer_r - ring_w - tick_len, cy)], fill=255, width=tick_w)
    d.line([(cx - outer_r + ring_w, cy), (cx - outer_r + ring_w + tick_len, cy)], fill=255, width=tick_w)
    
    rad = math.radians(35)
    ux, uy = math.sin(rad), -math.cos(rad)
    vx, vy = math.cos(rad), math.sin(rad)
    tip_len = 13.5 * S
    half_w = 4.5 * S
    n_tip = (cx + tip_len * ux, cy + tip_len * uy)
    s_tip = (cx - tip_len * ux, cy - tip_len * uy)
    e_corner = (cx + half_w * vx, cy + half_w * vy)
    w_corner = (cx - half_w * vx, cy - half_w * vy)
    
    d.polygon([n_tip, w_corner, e_corner], fill=255)
    d.polygon([s_tip, w_corner, e_corner], outline=255, width=int(1.8*S))
    d.ellipse([(cx - 2.8*S, cy - 2.8*S), (cx + 2.8*S, cy + 2.8*S)], fill=0)
    d.ellipse([(cx - 1.2*S, cy - 1.2*S), (cx + 1.2*S, cy + 1.2*S)], fill=255)


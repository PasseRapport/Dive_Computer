# 4. OPTIONS (Engrenage)
def draw_options(d, S):
    points = []
    for i in range(32):
        angle = 2*math.pi*i/32 - math.pi/2
        radius = 16 if i % 4 in (1,2) else 12
        points.append(((22+radius*math.cos(angle))*S, (22+radius*math.sin(angle))*S))
    d.line(points+[points[0]], fill=255, width=round(2.1*S), joint="curve")
    d.ellipse([(16.5*S,16.5*S),(27.5*S,27.5*S)], outline=255, width=round(2.1*S))


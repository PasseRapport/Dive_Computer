#!/usr/bin/env python3
"""Build and export all 8 native 44px icons for Dive Watch / LVGL 9 simulator.

Generates:
  - icon_drop.c     (Eau douce / Fresh water)
  - icon_wave.c     (Eau salée / Salt water)
  - icon_tank.c     (Bouteille / Scuba Cylinder)
  - icon_options.c  (Option / Settings Gear)
  - icon_apnea.c    (Apnée / Freediving Descent)
  - icon_scuba.c    (Plongée avec bouteilles / Scuba Diver)
  - icon_compass.c  (Boussole / Compass Bezel & Needle)
  - icon_watch.c    (Montre / Watch Dial)
"""
import math
from pathlib import Path
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
ASSETS_DIR = ROOT / 'src' / 'assets'
SIZE = 44
SCALE = 8

def path_bezier(start, segments):
    points = [start]
    for kind, *coords in segments:
        if kind == 'L':
            points.append(tuple(coords))
            continue
        x0, y0 = points[-1]
        x1, y1, x2, y2, x3, y3 = coords
        for i in range(1, 65):
            t = i / 64.0
            u = 1.0 - t
            points.append((
                u**3 * x0 + 3 * u**2 * t * x1 + 3 * u * t**2 * x2 + t**3 * x3,
                u**3 * y0 + 3 * u**2 * t * y1 + 3 * u * t**2 * y2 + t**3 * y3
            ))
    return [(round(x * SCALE), round(y * SCALE)) for x, y in points]

def render_and_save(name, draw_fn):
    mask = Image.new('L', (SIZE * SCALE, SIZE * SCALE), 0)
    draw = ImageDraw.Draw(mask)
    draw_fn(draw, SCALE)
    
    mask = mask.resize((SIZE, SIZE), Image.Resampling.LANCZOS)
    
    # White RGB + Alpha mask for clean LVGL recoloring without fringes
    payload = [channel for alpha in mask.tobytes() for channel in (255, 255, 255, alpha)]
    lines = [', '.join(f'0x{v:02x}' for v in payload[i:i+24]) for i in range(0, len(payload), 24)]
    
    source = '#include <lvgl.h>\n/* Native 44 px icon; generated by tools/build_all_icons.py. */\n'
    source += f'static const uint8_t {name}_data[] = {{\n    ' + ',\n    '.join(lines) + '\n};\n'
    source += f'''const lv_image_dsc_t {name} = {{
    .header = {{ .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_ARGB8888,
                .w = 44, .h = 44, .stride = 176 }},
    .data_size = sizeof({name}_data), .data = {name}_data,
}};
'''
    try:
        (ASSETS_DIR / f'{name}.c').write_text(source)
    except OSError:
        pass
    Path(f'/tmp/{name}.c').write_text(source)
    image = Image.new('RGBA', (SIZE, SIZE), 'white')
    image.putalpha(mask)
    image.save(f'/tmp/{name}-native.png')

# 1. DROP (Original Bézier)
def draw_drop(d, S):
    shapes = [
        (255, (22, 2), [('C', 19, 9, 7, 19, 7, 29), ('C', 7, 47, 37, 47, 37, 29), ('C', 37, 19, 25, 9, 22, 2)]),
        (0, (20, 12), [('C', 16, 18, 11, 24, 11, 30), ('C', 11, 33, 12, 35, 14, 36), ('C', 12, 26, 18, 20, 22, 15), ('L', 20, 12)])
    ]
    for val, start, segs in shapes:
        d.polygon(path_bezier(start, segs), fill=val)

